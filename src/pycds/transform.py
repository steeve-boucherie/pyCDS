# HELPER
class AtmosphericConstant(BaseModel):
    """
    Library of class of atmospheric constants useful for calculation.

    Constant are taken from Stull book "Practical Meteorology"
    See: Stull, R., 2017: "Practical Meteorology: An Algebra-based Survey \
        of Atmospheric Science" -version 1.02b.  Univ. of British Columbia. \
        940 pages.  isbn 978-0-88865-283-6 ."
    link: https://www.eoas.ubc.ca/books/Practical_Meteorology/
    """

    # Meta-config
    model_config = ConfigDict(frozen=True, extra='forbid')

    # Air specific constant (perfect gas)
    rd: float = 287.05  # J/kg/K
    # Water vapor specific constant
    rv: float = 461.52  # J/kg/K
    # Ratio of gaz constants of vapor and air
    eps: float = rd / rv
    # Water latent vaporization heat
    lv: float = 2.5e6  # J/kg
    # Freezing temperature (0°C) in Kelvin
    t0: float = 273.15  # K
    # Saturation vapor pressure at 0°C
    e0: float = 0.6113 * 1000  # Pa
    # Reference air density (for wind speed correction)
    rho_ref: float = 1.225


# UTILS
# ABSTRACT
class DataTransformerInterface(abc.ABC):
    """
    Abstract class for data transform.

    Notes
    -----
    Transform method is inspired from the fit and transform approach from
    scikit-learn.

    Parameters
    ----------
    mapper: KeyMapper | None
        (Optional) Custom mapper from aliases to dataset keys. Use the \
        package default if None is passed.

    Attributes
    ----------
    mapper: KeyMapper
        Instance of mapper class from dataset keys to standard aliases.
    _ds: Dataset
        (Internal) dataset used for passing argument to the transform method.
    """

    # Init
    def __init__(self, mapper: KeyMapper | None = None) -> None:
        """Create class instance."""
        self.mapper = mapper if mapper is not None else get_mapper()
        # Internal
        self._ds: xr.Dataset | None = None

    # Properties
    @property
    def name(self) -> str:
        """Return the class name."""
        return self.__class__.__name__

    @property
    @abc.abstractmethod
    def required_dims(self) -> list[str]:
        """List all dimensions that must be present in the dataset."""
        raise NotImplementedError

    @property
    @abc.abstractmethod
    def required_coords(self) -> list[str]:
        """List all coordinates that must be present in the dataset."""
        raise NotImplementedError

    @property
    @abc.abstractmethod
    def required_keys(self) -> list[str]:
        """List all keys that must be present in the dataset."""
        raise NotImplementedError

    @property
    @abc.abstractmethod
    def generated_keys(self) -> list[str]:
        """List all the keys that will be generated by the data filter."""
        raise NotImplementedError

    # Methods
    def validate_inputs(self, ds: xr.Dataset) -> None:
        """
        Validate that the input dataset contains the requested dimensions, \
        coordinates and keys, and raise a ValueError if otherwise.

        Parameters
        ----------
        ds: Dataset
            Input dataset to be tested.

        Raises
        ------
            ValueError
        """
        check_required(ds, self.required_dims, 'dim')
        check_required(ds, self.required_coords, 'coord')
        check_required(ds, self.required_keys, 'key')

    def fit(self, ds: xr.Dataset) -> 'DataTransformerInterface':
        """
        Pre-process data before running the "transform" step

        Parameters
        ----------
        ds: xr.Dataset
            Input dataset of turbine data.

        Returns
        -------
            DataTransformerInterface
        """
        # Check input and initialze internal variable
        self.validate_inputs(ds)
        self._ds = ds

        return self

    @abc.abstractmethod
    def transform(self, ds: xr.Dataset = None) -> xr.Dataset:
        """Append the transform to the dataset and return."""
        raise NotImplementedError

    def fit_transform(self, ds: xr.Dataset) -> xr.Dataset:
        """Chain the "fit" and "transform" steps."""
        return self.fit(ds).transform()


# CLASS
class Era5AirDensityCalculator(DataTransformerInterface):
    """
    Transformer class for calculation of the air density from ERA5 data using the \
    the ambient temperature, atmospheric pressure using correction for wet \
    air based on relative humidity.

    This class follows the method described in Floor and Nielsen (2019).
    See: https://www.mdpi.com/1996-1073/12/11/2038# for more details.

    The air density, rho, can be derived from the law of perfect gaz:

    >>> rho = P / (Rd * Tv)

    Where P is the atmospheric pressure in Pa, Rd = 287.05 J/kg/K is the gaz \
    constant for dry air, and Tv is the humidity-corrected temperature, in K, \
    and is given by:

    >>> Tv = (1 + 0.61 * q) * T

    Where T is the ambient temperature in K, and q is the specific humidity, \
    in kg/kg, and is by:

    >>> q = eps * e / P

    Where P is the atmospheric pressure in Pa, eps is the ratio of the air constant, \
    Rd, to the water vapor constant, Rv = 461 J/kg/K, and e is the saturation \
    vapor pressure. The latter can be computed from the dewpoint temperature, \
    available in ERA5, by the formula:

    >>> e = e0 * exp(Lv / Rv * (1 / T0 - 1 / Td))

    Where e0 = 661.3Pa, Lv=2.5e6 J/kg is the water latent vaporization heat, \
    T0= 273.15K, and Td is the dewpoint temperature in K.

    Calculation of the air density thus requires the following variables:
    - Atmospheric pressure, P, in Pa.
    - Ambient temperature, T, in K.
    - Dewpoint temperature, Td, in K.

    That can call be extracted from the ERA5 dataset.

    Parameters
    ----------
    cst: AtmosphericConstant | None
        (Optional) Custom atmospheric constant values. \
        Use the package default if None is passed.
    mapper: KeyMapper | None
        (Optional) Custom mapper from aliases to dataset keys. Use the \
        package default if None is passed.

    Attributes
    ----------
    cst: AtmosphericConstant
        Instance dataclass defining the atmospheric used in the calculation.
    mapper: KeyMapper
        Instance of mapper class from dataset keys to standard aliases.
    _ds: Dataset
        (Internal) dataset used for passing argument to the transform method.
    """

    def __init__(
        self,
        cst: AtmosphericConstant | None = None,
        mapper:  KeyMapper | None = None,
    ) -> None:
        """Create class instance."""
        super().__init__(mapper)
        self.cst = cst if cst is not None else AtmosphericConstant()

    # Properties
    @property
    def required_dims(self) -> list[str]:
        """List all dimensions that must be present in the dataset."""
        return [self.mapper.t_dim]

    @property
    def required_coords(self) -> list[str]:
        """List all coordinates that must be present in the dataset."""
        return []

    @property
    def required_keys(self) -> list[str]:
        """List all keys that must be present in the dataset."""
        return [self.mapper.sp_key, self.mapper.t2m_key, self.mapper.d2m_key]

    @property
    def generated_keys(self) -> list[str]:
        """List all the keys that will be generated by the data filter."""
        return [self.mapper.rho_key]

    # Methods
    def transform(self, ds: xr.Dataset = None) -> xr.Dataset:
        """
        Build filter and append to the dataset.

        Parameters
        ----------
        ds: xr.Dataset
            Input dataset of turbine data. - This is ignored.

        Returns
        -------
        new_ds: xr.Dataset
            Dataset with updated data.
        """
        ds = self._ds

        # Get the saturation vapor pressure
        e_da = (
            self.cst.e0 * np.exp(
                self.cst.lv / self.cst.rv
                * (1 / self.cst.t0 - 1 / ds[self.mapper.d2m_key])
            ))
        # Get the specific humidity
        q_da = self.cst.eps * e_da / ds[self.mapper.sp_key]
        # Correct temperature
        tv_da = (1 + 0.61 * q_da) * ds[self.mapper.t2m_key]
        # Density
        rho_da = ds[self.mapper.sp_key] / (self.cst.rd * tv_da)

        return self._ds.assign({self.mapper.rho_key: rho_da})


class WSCalculator(DataTransformerInterface):
    """
    Wrapper class to compute the wind speed magnitude from the horizontal \
        components of the wind speed.

    Parameters
    ----------
    mapper: KeyMapper | None
        (Optional) Custom mapper from aliases to dataset keys. Use the \
        package default if None is passed.

    Attributes
    ----------
    mapper: KeyMapper
        Instance of mapper class from dataset keys to standard aliases.
    _ds: Dataset
        (Internal) dataset used for passing argument to the transform method.
    """

    # Properties
    @property
    def required_dims(self) -> list[str]:
        """List all dimensions that must be present in the dataset."""
        return []

    @property
    def required_coords(self) -> list[str]:
        """List all coordinates that must be present in the dataset."""
        return []

    @property
    def required_keys(self) -> list[str]:
        """List all keys that must be present in the dataset."""
        return [self.mapper.u_key, self.mapper.v_key]

    @property
    def generated_keys(self) -> list[str]:
        """List all the keys that will be generated by the data filter."""
        return [self.mapper.ws_key]

    # Methods
    def transform(self, ds: xr.Dataset = None) -> xr.Dataset:
        """
        Build filter and append to the dataset.

        Parameters
        ----------
        ds: xr.Dataset
            Input dataset of turbine data. - This is ignored.

        Returns
        -------
        new_ds: xr.Dataset
            Dataset with updated data.
        """
        # Get variable
        u_da = self._ds[self.mapper.u_key]
        v_da = self._ds[self.mapper.v_key]

        # Compute
        ws_da = (u_da**2 + v_da**2)**.5

        # Assign
        out = self._ds.assign({self.mapper.ws_key: ws_da})

        return out


class WSDensityCorrector(DataTransformerInterface):
    """
    Class to compute density corrected wind speed from the SCADA data.

    Notes
    -----
    >>> ws_corr = ws * (rho / rho_ref)**(1 / 3)
    Where:
    - ws: is the actual wind speed measurement from SCADA.
    - rho: is the actual air density value from SCADA.
    - rho_ref: is the reference air density (defined by user).
    - ws_corr: is the density-corrected wind speed.

    Parameters
    ----------
    rho_ref: float | None
        (Optional) Custom value for the reference air density. \
        Use the package default if None is passed.
    mapper: KeyMapper | None
        (Optional) Custom mapper from aliases to dataset keys. Use the \
        package default if None is passed.


    Attributes
    ----------
    rho_ref: float
        Reference air density value.
    mapper: KeyMapper
        Instance of mapper class from dataset keys to standard aliases.
    _ds: Dataset
        (Internal) dataset used for passing argument to the transform method.
    """

    def __init__(
        self,
        rho_ref: float | None = None,
        mapper:  KeyMapper | None = None,
    ) -> None:
        """Create class instance."""
        super().__init__(mapper)
        self.rho_ref = (
            rho_ref if rho_ref is not None
            else AtmosphericConstant().rho_ref
        )

    # Properties
    @property
    def required_dims(self) -> list[str]:
        """List all dimensions that must be present in the dataset."""
        return [self.mapper.t_dim]

    @property
    def required_coords(self) -> list[str]:
        """List all coordinates that must be present in the dataset."""
        return []

    @property
    def required_keys(self) -> list[str]:
        """List all keys that must be present in the dataset."""
        return [self.mapper.ws_key, self.mapper.rho_key]

    @property
    def generated_keys(self) -> list[str]:
        """List all the keys that will be generated by the data filter."""
        return [self.mapper.ws_corr_key]

    # Methods
    def transform(self, ds: xr.Dataset = None) -> xr.Dataset:
        """
        Build filter and append to the dataset.

        Parameters
        ----------
        ds: xr.Dataset
            Input dataset of turbine data. - This is ignored.

        Returns
        -------
        new_ds: xr.Dataset
            Dataset with updated data.
        """
        # Compute density corrected ws
        da = (
            self._ds[self.mapper.ws_key]
            *
            (self._ds[self.mapper.rho_key] / self.rho_ref)**(1 / 3)
        )
        da = da.assign_attrs(
            rho_ref=str(self.rho_ref)
        )

        return self._ds.assign({self.mapper.ws_corr_key: da})


class WDirCalculator(DataTransformerInterface):
    """
    Wrapper class to compute the wind direction from the horizontal \
        components of the wind speed.

    Notes
    -----
    By convention wind directions is equal to 0° for northern wind \
        and increases in the clockwise direction.

    Parameters
    ----------
    unit: 'rad' | 'deg'
        An option defining whether the unit of output wind direction data is \
        expressed in radians ("rad") or degress ("deg"). \
        Default is degress ("deg").
    mapper: KeyMapper | None
        (Optional) Custom mapper from aliases to dataset keys. Use the \
        package default if None is passed.

    Attributes
    ----------
    unit: 'rad' | 'deg'
        An option defining whether the unit of output wind direction data is \
        expressed in radians ("rad") or degress ("deg"). \
        Default is degress ("deg").
    mapper: KeyMapper
        Instance of mapper class from dataset keys to standard aliases.
    _ds: Dataset
        (Internal) dataset used for passing argument to the transform method.
    """

    def __init__(
        self,
        unit: Literal['deg', 'rad'] = 'deg',
        mapper:  KeyMapper | None = None,
    ) -> None:
        """Create class instance."""
        super().__init__(mapper)
        allowed = ['deg', 'rad']
        if unit not in allowed:
            msg = f'Invalid value for attribute "unit". Must be one of {allowed}, ' \
                  f'but received: {unit}. Please check your inputs.'
            logger.error(msg)
            raise ValueError(msg)
        self.unit = unit

    # Properties
    @property
    def required_dims(self) -> list[str]:
        """List all dimensions that must be present in the dataset."""
        return [self.mapper.t_dim]

    @property
    def required_coords(self) -> list[str]:
        """List all coordinates that must be present in the dataset."""
        return []

    @property
    def required_keys(self) -> list[str]:
        """List all keys that must be present in the dataset."""
        return [self.mapper.u_key, self.mapper.v_key]

    @property
    def generated_keys(self) -> list[str]:
        """List all the keys that will be generated by the data filter."""
        return [self.mapper.wd_key]

    @property
    def factor(self) -> float:
        """Given the unit of the input wind direction, \
            return the conversion factor."""
        return {'rad': 1, 'deg': 180 / pi}[self.unit]

    # Methods
    def transform(self, ds: xr.Dataset = None) -> xr.Dataset:
        """
        Build filter and append to the dataset.

        Parameters
        ----------
        ds: xr.Dataset
            Input dataset of turbine data. - This is ignored.

        Returns
        -------
        new_ds: xr.Dataset
            Dataset with updated data.
        """
        # Get variable
        u_da = self._ds[self.mapper.u_key]
        v_da = self._ds[self.mapper.v_key]

        # Compute
        wd_da = ((np.atan2(u_da, v_da) + pi) % tau) * self.factor

        # Assign
        out = self._ds.assign({self.mapper.wd_key: wd_da})

        return out
